"""Notebook lifecycle templating with nbformat (U1).

The builder assembles a complete, standards-compliant nbformat 4.5 notebook:

  * mandatory dataset-license Markdown cell at the top (U5)
  * sectioned architecture: setup → data → model → training → inference
  * a dedicated BLIP captioning section for image models (U3)
  * metadata describing generation provenance and safety validation
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import nbformat
from nbformat.v4 import new_code_cell, new_markdown_cell, new_notebook

from .catalog import DATASETS, MODELS

GENERATOR_NAME = "GenAI Notebook Generator"
GENERATOR_VERSION = "1.0.0"


class NotebookBuildError(ValueError):
    pass


def _license_markdown(spec: dict[str, Any], generation_meta: dict[str, Any]) -> str:
    model = spec["model"]
    dataset = spec["dataset"]
    license_info = dataset["license"]
    commercial = "Yes" if license_info["commercial_use"] else "Check upstream terms"
    timestamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    source = generation_meta.get("source", "template")
    source_label = (
        f"LLM-assisted ({generation_meta.get('provider', 'unknown')} / "
        f"{generation_meta.get('llm_model', 'unknown')})"
        if source == "llm"
        else "Deterministic template (LLM disabled or unavailable)"
    )

    return f"""# {model["label"]} · {dataset["label"]}

**Generated by {GENERATOR_NAME} v{GENERATOR_VERSION}** · TensorFlow 2 / Keras · Google Colab ready  
Generated at **{timestamp}** · Seed **{spec["settings"]["seed"]}** · {spec["settings"]["epochs"]} epochs · batch size {spec["settings"]["batch_size"]}

> This notebook is machine-generated. Review every cell before running it in an
> environment that contains credentials or private data.

## Dataset license

| Field | Value |
| --- | --- |
| **Dataset** | {dataset["label"]} |
| **License** | **{license_info["name"]}** |
| **Attribution** | {license_info["attribution"]} |
| **Commercial use** | {commercial} |
| **License URL** | {license_info["url"]} |
| **Source** | {dataset["source_url"]} |
| **Citation** | {dataset["citation"]} |

**License notes:** {license_info["notes"]}

License information is injected from the generator's dataset registry for
convenience. It is not legal advice — verify the current upstream terms before
redistributing data or trained artifacts derived from it.

## Safety & validation

- All Python cells were parsed with `ast` and statically checked for syntax errors.
- Imports and calls matching the malicious-code policy are rejected.
- TF1-only patterns (`tf.compat.v1`, `tf.Session`, `tf.placeholder`, standalone
  Keras imports) are rejected.
- Shell magics are allow-listed; this notebook only installs pinned, trusted
  packages.
- Code generation path: **{source_label}**.

## How to run

1. Upload this `.ipynb` to [Google Colab](https://colab.research.google.com/).
2. Select **Runtime → Change runtime type → T4 GPU** (recommended).
3. Select **Runtime → Run all**. Training defaults to {spec["settings"]["epochs"]}
   epoch(s); increase `EPOCHS` in the setup cell for better samples.
"""


def build_notebook(
    spec: dict[str, Any],
    *,
    llm_overrides: dict[str, str] | None = None,
    generation_meta: dict[str, Any] | None = None,
) -> nbformat.NotebookNode:
    """Assemble a notebook from a template spec plus optional LLM overrides."""

    overrides = llm_overrides or {}
    generation_meta = generation_meta or {"source": "template"}
    model = spec["model"]
    dataset = spec["dataset"]
    sections = spec["sections"]

    unknown = set(overrides) - {section["key"] for section in sections if section["llm_editable"]}
    if unknown:
        raise NotebookBuildError(f"LLM overrides target non-editable sections: {sorted(unknown)}")

    metadata = {
        "colab": {
            "provenance": [],
            "gpuType": "T4",
            "toc_visible": True,
        },
        "kernelspec": {"name": "python3", "display_name": "Python 3"},
        "language_info": {"name": "python", "mimetype": "text/x-python"},
        "genai": {
            "generator": GENERATOR_NAME,
            "version": GENERATOR_VERSION,
            "model": model["id"],
            "model_label": model["label"],
            "model_kind": model["kind"],
            "dataset": dataset["id"],
            "dataset_label": dataset["label"],
            "license": dataset["license"]["name"],
            "settings": spec["settings"],
            "generation": {
                key: value
                for key, value in generation_meta.items()
                if key in {"source", "provider", "llm_model", "fallback_reason"}
            },
        },
    }

    notebook = new_notebook(metadata=metadata)

    cells: list[Any] = []
    license_cell = new_markdown_cell(_license_markdown(spec, generation_meta))
    license_cell.metadata["genai_section"] = "license"
    cells.append(license_cell)

    for section in sections:
        key = section["key"]
        markdown = f"## {section['title']}\n\n{section['markdown']}\n"
        markdown_cell = new_markdown_cell(markdown)
        markdown_cell.metadata["genai_section"] = key
        cells.append(markdown_cell)

        if key in overrides:
            code_sources = [overrides[key]]
            from_llm = True
        else:
            code_sources = section["code"]
            from_llm = False

        for source in code_sources:
            code_cell = new_code_cell(source)
            code_cell.metadata["genai_section"] = key
            code_cell.metadata["genai_llm_generated"] = from_llm
            cells.append(code_cell)

    notebook.cells = cells
    return notebook


def notebook_to_dict(notebook: nbformat.NotebookNode) -> dict[str, Any]:
    """Round-trip through nbformat's JSON writer for a clean plain dict."""

    return json.loads(nbformat.writes(notebook))


def notebook_filename(model_key: str, dataset_key: str) -> str:
    model = MODELS.get(model_key, {"id": model_key})
    dataset = DATASETS.get(dataset_key, {"id": dataset_key})
    model_slug = model["id"].replace("-", "_")
    dataset_slug = dataset["id"].replace("-", "_")
    return f"{model_slug}_{dataset_slug}.ipynb"


def write_notebook(notebook: nbformat.NotebookNode, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    nbformat.write(notebook, str(path))
    return path
